import { execFileSync } from 'node:child_process'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { createMarkdownFromOpenApi } from '@scalar/openapi-to-markdown'

const platformDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const goPlatformDir = path.join(platformDir, 'go-platform')
const outputPath = path.join(platformDir, 'docs', 'API.md')

function exportOpenApi(service) {
  const output = execFileSync(
    'go',
    ['run', './cmd/openapi-export', '-service', service],
    { cwd: goPlatformDir, encoding: 'utf8' },
  )
  return JSON.parse(output)
}

const documents = [
  ['Gateway API', exportOpenApi('gateway')],
  ['Admin API', exportOpenApi('admin')],
]

const sections = []
for (const [title, document] of documents) {
  const markdown = await createMarkdownFromOpenApi(document)
  sections.push(`## ${title}\n\n${markdown.trim()}`)
}

const generated = `<!-- Code generated by the api-docs CI job; DO NOT EDIT. -->

# ADP API

> Этот файл автоматически сформирован из текущих OpenAPI-документов Go-сервисов. Он отражает только уже описанную в OpenAPI часть API.

${sections.join('\n\n---\n\n')}
`

await mkdir(path.dirname(outputPath), { recursive: true })
await writeFile(outputPath, generated, 'utf8')
