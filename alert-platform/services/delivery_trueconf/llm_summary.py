"""Саммаризация инцидента через локальную LLM — раздел 13, сценарий 4.

Раздел 13 (важно): "выводы моделей помечены как гипотеза, ... не находятся
на критическом пути доставки и самостоятельно не приводят к неотправке
сообщения". Поэтому здесь только формирование ТЕКСТА сводки — она либо
дополняет детерминированное SUPPLEMENT-сообщение (раздел 9.3), либо, при
отказе/таймауте LLM, просто отсутствует, а раздел с фактами (правило,
первопричина, счётчики) всё равно уходит.

Модель — `log-reader` (локальный Ollama на этом же сервере, раздел 1.4:
открытые веса, без обращений к внешним API). Модель развёрнута отдельно
от этого проекта, но её системный промпт (разбор логов: первопричина vs
симптомы, оценка уверенности, запрет выдумывать факты) подходит для этой
задачи почти без адаптации — переиспользуем как есть, без своего system.
"""
from __future__ import annotations

from packages.ai.client import ask


def build_prompt(*, root_symptom: str, root_object: str, root_site: str, opened_at: str,
                  symptoms: list[tuple[str, str]], rule_names: list[str]) -> str:
    # Приоритет намеренно НЕ передаётся модели: живой прогон (2026-08-06)
    # показал, что модель может неверно назвать переданное значение
    # приоритета (P3 в данных → P2 в ответе) — не выдумка из пустоты, а
    # искажение реального факта. Раз приоритет уже верно виден в шапке
    # исходного NEW-сообщения, риск лучше просто убрать, чем держать под
    # меткой "гипотеза".
    symptoms_lines = "\n".join(f"- {name} ({symptom_class})" for name, symptom_class in symptoms)
    rules = ", ".join(rule_names) or "не определено"
    return (
        f"Инцидент мониторинга промышленного предприятия.\n"
        f"Первопричина (кандидат): {root_object} на площадке {root_site}, "
        f"симптом {root_symptom}, зафиксировано {opened_at}.\n"
        f"Связанные симптомы ({len(symptoms)}):\n{symptoms_lines}\n"
        f"Правило корреляции: {rules}.\n\n"
        f"Дай короткую сводку для дежурного инженера: 2-4 предложения, только факты "
        f"из данных выше, без домыслов. Не используй списки и заголовки — сплошной текст. "
        f"Не упоминай приоритет и не оценивай критичность — это не входит в переданные данные."
    )


async def summarize_incident(prompt: str) -> str | None:
    return await ask(prompt)
